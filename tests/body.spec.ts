import { test, expect } from '@playwright/test'

const daysAgo = (n: number) => { const d = new Date(Date.now() - n * 86400000); return new Date(d.getTime() - d.getTimezoneOffset() * 60000).toISOString().slice(0, 16) }
const scale = { 'Índice de masa corporal (IMC)': '29,6', 'Grasa corporal': '41.7', 'Agua': '42.3', 'Músculo': '52.2', 'Masa ósea': '2.6' }

test('báscula: validación, resumen, gráfica, historial, CSV, edición y eliminación', async ({ page, context }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /^Peso y composición/ }).click()
  await expect(page.getByText('¿Estabas en ayunas?')).toHaveCount(0)
  await page.getByRole('button', { name: 'Guardar pesaje', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Escribe tu peso')
  await page.getByLabel('¿Cuánto marcó tu báscula?').fill('68,9')
  await page.getByLabel('Grasa corporal').fill('140')
  await page.getByRole('button', { name: 'Guardar pesaje', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Grasa corporal')
  await page.getByLabel('Grasa corporal').fill('')
  await page.getByRole('button', { name: 'Cambiar', exact: true }).click()
  await page.getByLabel('Fecha y hora de la medición', { exact: true }).fill(daysAgo(60))
  await page.getByRole('button', { name: 'Guardar pesaje', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Pesaje guardado')
  await context.setOffline(true)
  await page.getByLabel('¿Cuánto marcó tu báscula?').fill('68.5')
  for (const [label, value] of Object.entries(scale)) await page.getByLabel(label, { exact: true }).fill(value)
  await page.getByRole('button', { name: 'Guardar pesaje', exact: true }).click()
  await expect(page.locator('.latest-value')).toContainText('68.5')
  await expect(page.locator('.body-latest')).toContainText('−0.4 kg desde el pesaje anterior')
  await expect(page.locator('.body-mini')).toContainText('41.7%')
  await expect(page.locator('.body-mini')).toContainText('2.6 kg')
  await expect(page.getByRole('button', { name: /^Peso y composición/ })).toContainText('68.5')
  await page.getByRole('button', { name: '30 días' }).click()
  await page.getByRole('button', { name: 'Grasa', exact: true }).click()
  await expect(page.getByText('Con al menos dos mediciones')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: test.info().outputPath('body.png'), fullPage: true })
  await context.setOffline(false)
  await page.reload()
  await page.getByRole('button', { name: /^Peso y composición/ }).click()
  await expect(page.locator('.latest-value')).toContainText('68.5')
  await page.getByRole('button', { name: 'Mis mediciones', exact: true }).click()
  await page.getByRole('combobox', { name: 'Tipo', exact: true }).selectOption('body')
  await expect(page.getByText('2 registros', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Momento')).toBeDisabled()
  await expect(page.getByText('IMC 29.6 · Grasa 41.7% · Agua 42.3% · Músculo 52.2% · Hueso 2.6 kg')).toBeVisible()
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar CSV' }).click()
  const stream = await (await pending).createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(chunk)
  expect(Buffer.concat(chunks).toString('utf8')).toContain('"Peso y composición","","","","kg","","68.5","29.6","41.7","42.3","52.2","2.6"')
  await page.getByRole('button', { name: 'Editar pesaje de 68.9 kg', exact: true }).click()
  await page.getByRole('dialog').getByLabel('¿Cuánto marcó tu báscula?').fill('69')
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: 'Eliminar pesaje de 69 kg', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Eliminar pesaje', exact: true }).click()
  await expect(page.getByText('1 registros', { exact: true })).toBeVisible()
})

test('perfil: edad, estatura e IMC calculado', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Ajustes', exact: true }).click()
  await page.getByLabel('Nombre').fill('María Dolores')
  await page.getByLabel('Fecha de nacimiento').fill('1960-03-10')
  await page.getByLabel('Sexo').selectOption('F')
  await page.getByLabel('Estatura (cm)').fill('500')
  await page.getByRole('button', { name: 'Guardar mis datos' }).click()
  await expect(page.getByRole('alert')).toContainText('centímetros')
  await page.getByLabel('Estatura (cm)').fill('152')
  await page.getByRole('button', { name: 'Guardar mis datos' }).click()
  await expect(page.getByRole('status')).toContainText('Tus datos se guardaron')
  await page.reload()
  await page.getByRole('button', { name: 'Ajustes', exact: true }).click()
  await expect(page.getByLabel('Estatura (cm)')).toHaveValue('152')
  await expect(page.locator('.profile-form small')).toContainText('años')
  await page.getByRole('button', { name: 'Mi resumen', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Hola, María.' })).toBeVisible()
  await page.getByRole('button', { name: /^Peso y composición/ }).click()
  await page.getByLabel('¿Cuánto marcó tu báscula?').fill('68.5')
  await expect(page.locator('.body-hint')).toContainText('29.6')
  await page.getByRole('button', { name: 'Guardar pesaje', exact: true }).click()
  await expect(page.locator('.body-mini')).toContainText('29.6')
})
