import { test, expect } from '@playwright/test'

test('momentos de glucosa, pulso y aviso de duplicados', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('¿Qué valor marcó tu glucómetro?').fill('142')
  await page.getByRole('button', { name: '2 h después de comer', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar medición', exact: true }).click()
  await expect(page.locator('.latest-card')).toContainText('2 h después de comer')
  await page.getByLabel('¿Qué valor marcó tu glucómetro?').fill('142')
  await page.getByRole('button', { name: '2 h después de comer', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar medición', exact: true }).click()
  await expect(page.locator('.form-warning')).toContainText('Ya hay una medición de 142')
  await page.getByRole('button', { name: 'Guardar de todos modos' }).click()
  await expect(page.getByRole('status')).toContainText('Medición guardada')
  await page.getByRole('button', { name: /^Presión arterial/ }).click()
  await page.getByLabel('Sistólica (mmHg)', { exact: true }).fill('124')
  await page.getByLabel('Diastólica (mmHg)', { exact: true }).fill('79')
  await page.getByLabel('Pulso', { exact: true }).fill('300')
  await page.getByRole('button', { name: 'Guardar medición', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('pulso')
  await page.getByLabel('Pulso', { exact: true }).fill('72')
  await page.getByRole('button', { name: 'Guardar medición', exact: true }).click()
  await expect(page.locator('.latest-card')).toContainText('Pulso 72 lpm')
  await page.getByRole('button', { name: 'Mis mediciones', exact: true }).click()
  await page.getByLabel('Momento').selectOption('after_meal')
  await expect(page.getByText('2 registros', { exact: true })).toBeVisible()
  await page.getByLabel('Momento').selectOption('all')
  await expect(page.locator('.chip', { hasText: 'Pulso' })).toHaveText('Pulso 72 lpm')
  const records = await page.evaluate(() => JSON.parse(localStorage.getItem('salud100.readings.v1')!))
  expect(records.find((r: { unit: string }) => r.unit === 'mmHg').pulse).toBe(72)
  expect(records.find((r: { unit: string }) => r.unit === 'mg/dL')).toMatchObject({ moment: 'after_meal', fasting: false })
})

test('metas en la gráfica y resumen para el médico', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Ajustes', exact: true }).click()
  await page.getByLabel('Nombre').fill('María Dolores')
  await page.getByRole('button', { name: 'Guardar mis datos' }).click()
  await expect(page.getByRole('status')).toContainText('Tus datos se guardaron')
  await page.getByLabel('Glucosa mínima (mg/dL)').fill('130')
  await page.getByLabel('Glucosa máxima (mg/dL)').fill('80')
  await page.getByRole('button', { name: 'Guardar mis metas' }).click()
  await expect(page.getByRole('alert')).toContainText('menor que el máximo')
  await page.getByLabel('Glucosa mínima (mg/dL)').fill('80')
  await page.getByLabel('Glucosa máxima (mg/dL)').fill('130')
  await page.getByLabel('Sistólica máxima (mmHg)').fill('130')
  await page.getByLabel('Diastólica máxima (mmHg)').fill('80')
  await page.getByRole('button', { name: 'Guardar mis metas' }).click()
  await expect(page.getByRole('status')).toContainText('Tus metas se guardaron')
  await expect(page.getByLabel('Nombre')).toHaveValue('María Dolores')
  await page.getByRole('button', { name: 'Mi resumen', exact: true }).click()
  for (const [value, moment] of [['96', 'En ayunas'], ['150', '2 h después de comer']]) {
    await page.getByLabel('¿Qué valor marcó tu glucómetro?').fill(value)
    await page.getByRole('button', { name: moment, exact: true }).click()
    await page.getByRole('button', { name: 'Guardar medición', exact: true }).click()
    await expect(page.locator('.latest-value')).toContainText(value)
  }
  await expect(page.locator('.chart-card')).toContainText('Tu meta')
  await expect(page.locator('.chart-card rect')).toHaveCount(1)
  await page.getByRole('button', { name: 'Mis mediciones', exact: true }).click()
  await page.getByRole('button', { name: 'Resumen para el médico' }).click()
  const sheet = page.locator('.report-sheet')
  await expect(sheet).toContainText('María Dolores')
  await expect(sheet.locator('.report-table').first()).toContainText('123')
  await expect(sheet).toContainText('Meta indicada: 80–130 mg/dL')
  await expect(sheet.locator('.report-table').first().locator('tr', { hasText: 'Todas' })).toContainText('50% (1 de 2)')
  await expect(sheet).toContainText('Todos los registros')
  await expect(page.getByRole('button', { name: 'Imprimir o guardar PDF' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: test.info().outputPath('report.png'), fullPage: true })
  await page.emulateMedia({ media: 'print' })
  await expect(page.locator('.sidebar')).toBeHidden()
  await expect(page.getByRole('button', { name: 'Imprimir o guardar PDF' })).toBeHidden()
})
